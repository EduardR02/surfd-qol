"""Regenerate src/hud-fonts.js from the Instrument Sans TTFs (SIL OFL 1.1).

Usage (needs fontTools):  python dev/subset-fonts.py <dir-with-InstrumentSans-*.ttf>
Each face is subset to the characters the HUD and settings panel use and
embedded as base64 WOFF, so the extension makes no font requests at runtime.
"""
import base64, io, pathlib, sys
from fontTools import subset
from fontTools.ttLib import TTFont

TEXT_RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x2009, 0x200A), (0x2010, 0x2027), (0x2030, 0x2030),
               (0x2039, 0x203A), (0x2190, 0x2193), (0x2212, 0x2212), (0x2264, 0x2265), (0x202F, 0x202F)]
FACES = [  # (file, weight, style, ranges)
    ('InstrumentSans-Regular.ttf', '400', 'normal', TEXT_RANGES),
    ('InstrumentSans-Bold.ttf', '700', 'normal', TEXT_RANGES),
]

def woff(path, ranges):
    font = TTFont(path)
    options = subset.Options()
    options.layout_features = ['kern', 'tnum', 'case', 'liga', 'calt', 'ccmp', 'mark', 'mkmk']
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]  # keep copyright + license fields
    options.flavor = 'woff'
    options.with_zopfli = False
    sub = subset.Subsetter(options)
    sub.populate(unicodes=[c for a, b in ranges for c in range(a, b + 1)])
    sub.subset(font)
    out = io.BytesIO()
    font.flavor = 'woff'
    font.save(out)
    return out.getvalue()

source = pathlib.Path(sys.argv[1])
target = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'hud-fonts.js'
lines = [
    '// Generated by dev/subset-fonts.py. Do not edit by hand.',
    '/*! Instrument Sans: Copyright 2022 The Instrument Sans Project Authors',
    ' * (https://github.com/Instrument/instrument-sans). Licensed under the SIL',
    ' * Open Font License 1.1 (https://openfontlicense.org). Subset to the',
    ' * characters this extension renders. */',
    'export const fontFaces = [',
]
for file, weight, style, ranges in FACES:
    data = base64.b64encode(woff(source / file, ranges)).decode('ascii')
    lines.append(f"  {{weight: '{weight}', style: '{style}', data: '{data}'}},")
    print(file, len(data), 'base64 chars')
lines.append('];')
target.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
print('wrote', target)
